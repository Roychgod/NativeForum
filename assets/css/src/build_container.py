#!/usr/bin/env python3
"""Build assets/css/sf-container.css (dev tool, not loaded at runtime).

The forum's responsive rules use viewport @media (max-width:N). When the forum sits inside a narrow
column of the site's layout (site layout mode), the viewport is wide but the forum is narrow, so the
mobile rules never kick in. This copies every max-width rule and scopes it to a class the browser sets
on .sf-wrap from the forum's own width (.sf-cq-N = forum width <= N px).
"""
import re, os, json
HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
SOURCES = [  # (file, extra wrapper class that limits the rules to the theme that loads the file)
  ('assets/css/sf-bs-compat.css', ''),
  ('assets/css/sf-extras.css', ''),
  ('assets/css/sf-layout-fixes.css', ''),
  ('assets/css/sf-modern.css', ''),
  ('assets/css/sf-compact.css', ''),
  ('template-files/native-forum.css', '.sf-theme-simple'),
  ('template-files/native-forum-bootstrap.css', '.sf-wrap-bootstrap'),
]
MQ = re.compile(r'^\s*(?:only\s+)?(?:screen\s+and\s+)?\(\s*max-width\s*:\s*([\d.]+)px\s*\)\s*$', re.I)

def strip_comments(css): return re.sub(r'/\*.*?\*/', '', css, flags=re.S)

def blocks(css):
    """Yield (prelude, body) for top-level blocks."""
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: return
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == '{': depth += 1
            elif css[k] == '}': depth -= 1
            k += 1
        yield prelude, css[j+1:k-1]
        i = k

def scope(sel, cls):
    sel = sel.strip()
    if not sel or re.match(r'^(html|body|:root)\b', sel): return None
    if re.search(r'\.sf-wrap(?![\w-])', sel):
        return re.sub(r'\.sf-wrap(?![\w-])', '.sf-wrap' + cls, sel, count=1)
    return '.sf-wrap' + cls + ' ' + sel

out, bps = [], set()
for rel, themecls in SOURCES:
    path = os.path.join(MOD, rel)
    if not os.path.exists(path): continue
    css = strip_comments(open(path, encoding='utf-8').read())
    for prelude, body in blocks(css):
        if not prelude.lower().startswith('@media'): continue
        m = MQ.match(prelude[6:])
        if not m: continue
        w = float(m.group(1)); n = int(w)
        cls = themecls + '.sf-cq-%d' % n
        rules = []
        for sp, decl in blocks(body):
            if sp.startswith('@'): continue
            sels = [s for s in (scope(x, cls) for x in sp.split(',')) if s]
            if sels and decl.strip(): rules.append(',\n'.join(sels) + '{' + decl.strip() + '}')
        if rules:
            bps.add(n)
            out.append('/* %s  @media (max-width:%spx) */\n' % (rel, m.group(1)) + '\n'.join(rules))
hdr = ('/* GENERATED by assets/css/src/build_container.py — do not edit.\n'
       '   Mobile rules applied by the forum\'s own width (site layouts with narrow content columns).\n'
       '   Breakpoints: %s */\n' % json.dumps(sorted(bps)))
open(os.path.join(MOD, 'assets/css/sf-container.css'), 'w', encoding='utf-8').write(hdr + '\n\n'.join(out) + '\n')
print('breakpoints', sorted(bps), 'blocks', len(out))
